-- ─── Grants ──────────────────────────────────────────────────────────────────
-- Supabase grants broad table access to anon/authenticated by default; RLS above
-- decides. Functions: nothing for anon, and only the app's entry points for users.

revoke all on all tables    in schema public from anon;
revoke all on all functions in schema public from public, anon;
grant select, insert, update, delete on public.categories, public.items, public.bom_lines to authenticated;
grant select on public.checkout_log, public.profiles to authenticated;
grant execute on function
  public.adjust_qty(bigint, text, numeric),
  public.save_bom(bigint, jsonb),
  public.checkout(bigint, numeric, text),
  public.admin_list_users(),
  public.admin_invite(text, text),
  public.admin_cancel_invite(text),
  public.admin_set_role(uuid, text),
  public.admin_delete_user(uuid),
  public.bom_cost(bigint),
  public.my_role(),
  public.has_role(text),
  public.role_rank(text),
  public.require_admin(),
  public.bom_ancestors(bigint[])
  to authenticated;

